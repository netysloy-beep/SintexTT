import { PrismaClient } from '@prisma/client';
import { RESOURCE_KINDS, BASE_PRICES } from '../src/economy/catalog.js';

const prisma = new PrismaClient();

async function main(): Promise<void> {
  // Idempotent seed: ensure market prices exist for every resource kind.
  for (const kind of RESOURCE_KINDS) {
    const price = BASE_PRICES[kind];
    if (!price) throw new Error(`Missing base price for ${kind}`);
    await prisma.marketPrice.upsert({
      where: { kind },
      create: { kind, price },
      update: {},
    });
  }
  // A sample guild contract source NPC pool requires nothing pre-created:
  // guild contracts are generated by the worker for existing guilds.
  console.log(`Seeded market prices for ${RESOURCE_KINDS.length} resources.`);
}

main()
  .then(() => prisma.$disconnect())
  .catch(async (err) => {
    console.error(err);
    await prisma.$disconnect();
    process.exit(1);
  });
